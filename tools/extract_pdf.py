"""Extract pages from a privately owned PDF for study/reference only.

This is a local developer tool. It is excluded from the Android package and
must never be used to redistribute copyrighted workbook pages.

Requires PyMuPDF (not a runtime dependency of the app):

    python -m pip install pymupdf
    python tools/extract_pdf.py ~/Downloads/book.pdf --out refs/book --first 1 --last 20

The app itself does not need these images: all exercises are generated by
app/engine/generator.py.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("pdf", type=Path, help="path to a PDF you own")
    parser.add_argument("--out", type=Path, default=Path("refs/pages"), help="output directory")
    parser.add_argument("--first", type=int, default=1, help="first page (1-based)")
    parser.add_argument("--last", type=int, default=0, help="last page (0 = end)")
    parser.add_argument("--dpi", type=int, default=120, help="render resolution")
    parser.add_argument("--text", action="store_true", help="also write extracted text (if any)")
    parser.add_argument("--list", action="store_true", help="only list page count and metadata")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        import fitz  # PyMuPDF
    except ImportError:
        print("PyMuPDF is required: python -m pip install pymupdf", file=sys.stderr)
        return 2

    if not args.pdf.is_file():
        print(f"not found: {args.pdf}", file=sys.stderr)
        return 2

    with fitz.open(args.pdf) as document:
        total = document.page_count
        print(f"{args.pdf.name}: {total} pages, metadata={document.metadata.get('title') or '-'}")
        if args.list:
            return 0

        first = max(1, args.first)
        last = total if args.last <= 0 else min(total, args.last)
        if first > last:
            print("empty page range", file=sys.stderr)
            return 2

        args.out.mkdir(parents=True, exist_ok=True)
        scale = args.dpi / 72
        written = 0
        for number in range(first, last + 1):
            page = document.load_page(number - 1)
            pixmap = page.get_pixmap(matrix=fitz.Matrix(scale, scale), alpha=False)
            target = args.out / f"page-{number:04d}.png"
            pixmap.save(target)
            if args.text:
                text = page.get_text("text").strip()
                if text:
                    (args.out / f"page-{number:04d}.txt").write_text(text, encoding="utf-8")
            written += 1
        print(f"wrote {written} page(s) to {args.out}")
        print("Keep these files local; do not commit or redistribute them.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
