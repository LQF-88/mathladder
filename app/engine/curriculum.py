LEVEL_BY_CODE = {level.code: level for level in LEVELS}
TOPIC_BY_KEY = {topic.key: topic for level in LEVELS for topic in level.topics}


def level_of(code: str) -> Level:
    return LEVEL_BY_CODE[code]


def topic_of(key: str) -> Topic:
    return TOPIC_BY_KEY[key]
